import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

/**
 * Normalizes a commit SHA to a safe 7-character short identifier or 'local'.
 */
export function normalizeCommitSha(rawSha) {
  if (typeof rawSha !== 'string') {
    return null;
  }
  const cleaned = rawSha.trim().replace(/[^a-zA-Z0-9]/g, '');
  if (cleaned.length < 4) {
    return null;
  }
  return cleaned.slice(0, 7).toLowerCase();
}

/**
 * Resolves appVersion from package.json and short buildCommit from CI/Amplify env or git HEAD.
 */
export function resolveBuildMetadata({
  rootDir = projectRoot,
  env = process.env,
  gitRunner = (cwd) =>
    execSync('git rev-parse --short=7 HEAD', {
      cwd,
      stdio: ['ignore', 'pipe', 'ignore'],
      encoding: 'utf-8',
    }),
} = {}) {
  let appVersion = '0.0.0';
  try {
    const pkgPath = path.join(rootDir, 'package.json');
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
    if (typeof pkg.version === 'string' && pkg.version.trim() !== '') {
      appVersion = pkg.version.trim();
    }
  } catch {
    appVersion = '0.0.0';
  }

  const envCommit =
    normalizeCommitSha(env.AWS_COMMIT_ID) ||
    normalizeCommitSha(env.GITHUB_SHA) ||
    normalizeCommitSha(env.COMMIT_SHA);

  if (envCommit) {
    return { appVersion, buildCommit: envCommit };
  }

  try {
    const gitCommit = normalizeCommitSha(gitRunner(rootDir));
    if (gitCommit) {
      return { appVersion, buildCommit: gitCommit };
    }
  } catch {
    // Fallback to 'local' when git metadata is unavailable
  }

  return { appVersion, buildCommit: 'local' };
}

export function formatEnvironmentFile({ baseUrl, appVersion, buildCommit }) {
  return `// Auto-generated by scripts/generate-environment.mjs at build time
export const environment = {
  baseUrl: '${baseUrl}',
  appVersion: '${appVersion}',
  buildCommit: '${buildCommit}',
};
`;
}

export function generateProductionEnvironment({
  rootDir = projectRoot,
  env = process.env,
  gitRunner,
} = {}) {
  const apiBaseUrl = env.API_BASE_URL;

  console.log('[generate-environment] Checking API_BASE_URL configuration...');

  if (!apiBaseUrl || apiBaseUrl.trim() === '') {
    throw new Error(
      'API_BASE_URL environment variable is required for production build.',
    );
  }

  let parsedUrl;
  try {
    parsedUrl = new URL(apiBaseUrl.trim());
  } catch {
    throw new Error(`API_BASE_URL is not a valid URL: "${apiBaseUrl}"`);
  }

  if (parsedUrl.protocol !== 'https:' && parsedUrl.protocol !== 'http:') {
    throw new Error(
      `API_BASE_URL must use HTTP or HTTPS protocol. Received: "${apiBaseUrl}"`,
    );
  }

  if (parsedUrl.protocol === 'http:') {
    console.warn(
      `[generate-environment] WARNING: API_BASE_URL is using HTTP (${apiBaseUrl}). Note that browsers may block HTTP requests from HTTPS sites due to Mixed Content policies.`,
    );
  }

  // Normalize base URL and preserve /api/v1 path
  const origin = parsedUrl.origin;
  let pathname = parsedUrl.pathname.replace(/\/+$/, '');
  if (!pathname || pathname === '') {
    pathname = '/api/v1';
  }

  const normalizedBaseUrl = `${origin}${pathname}`;
  const { appVersion, buildCommit } = resolveBuildMetadata({
    rootDir,
    env,
    gitRunner,
  });

  const envDir = path.join(rootDir, 'src', 'environments');
  const targetFile = path.join(envDir, 'environment.production.ts');

  if (!fs.existsSync(envDir)) {
    fs.mkdirSync(envDir, { recursive: true });
  }

  const fileContent = formatEnvironmentFile({
    baseUrl: normalizedBaseUrl,
    appVersion,
    buildCommit,
  });

  fs.writeFileSync(targetFile, fileContent, 'utf-8');

  console.log(
    `[generate-environment] SUCCESS: Generated ${targetFile} (baseUrl: ${normalizedBaseUrl}, version: v${appVersion}, build: ${buildCommit})`,
  );

  return { targetFile, baseUrl: normalizedBaseUrl, appVersion, buildCommit };
}

const isDirectExecution =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename);

if (isDirectExecution) {
  try {
    generateProductionEnvironment();
  } catch (err) {
    console.error(`[generate-environment] ERROR: ${err.message}`);
    process.exit(1);
  }
}
