import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const apiBaseUrl = process.env.API_BASE_URL;

console.log('[generate-environment] Checking API_BASE_URL configuration...');

if (!apiBaseUrl || apiBaseUrl.trim() === '') {
  console.error('[generate-environment] ERROR: API_BASE_URL environment variable is required for production build.');
  process.exit(1);
}

let parsedUrl;
try {
  parsedUrl = new URL(apiBaseUrl.trim());
} catch (err) {
  console.error(`[generate-environment] ERROR: API_BASE_URL is not a valid URL: "${apiBaseUrl}"`);
  process.exit(1);
}

if (parsedUrl.protocol !== 'https:' && parsedUrl.protocol !== 'http:') {
  console.error(`[generate-environment] ERROR: API_BASE_URL must use HTTP or HTTPS protocol. Received: "${apiBaseUrl}"`);
  process.exit(1);
}

if (parsedUrl.protocol === 'http:') {
  console.warn(`[generate-environment] WARNING: API_BASE_URL is using HTTP (${apiBaseUrl}). Note that browsers may block HTTP requests from HTTPS sites due to Mixed Content policies.`);
}

// Normalize base URL and preserve /api/v1 path
const origin = parsedUrl.origin;
let pathname = parsedUrl.pathname.replace(/\/+$/, '');
if (!pathname || pathname === '') {
  pathname = '/api/v1';
}

const normalizedBaseUrl = `${origin}${pathname}`;

const envDir = path.join(projectRoot, 'src', 'environments');
const targetFile = path.join(envDir, 'environment.production.ts');

if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}

const fileContent = `// Auto-generated by scripts/generate-environment.mjs at build time
export const environment = {
  baseUrl: '${normalizedBaseUrl}',
};
`;

fs.writeFileSync(targetFile, fileContent, 'utf-8');

console.log(`[generate-environment] SUCCESS: Generated ${targetFile} with baseUrl: ${normalizedBaseUrl}`);
